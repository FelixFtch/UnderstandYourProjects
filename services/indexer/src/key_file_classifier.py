#!/usr/bin/env python3
"""Key-file classifier: a zero-model importance pre-filter that runs BEFORE Laya.

Why: Laya + qwen enrichment cost ~27 s per file on the Jetson, and almost every
code/doc file used to reach them (a ~3000-file project took ~18 h).  Tracking
project progress only needs the files that carry the project: entry points,
core modules, central imports, recently-touched work, top-level design docs.

How (stdlib only, no new packages, no GPU, ~ms per project):
  stage 0  hard gates   -> vendored / generated / minified / lockfile / sourcemap
                           paths and header markers (rules adapted from GitHub
                           Linguist vendor.yml + generated.rb and the repomix
                           default ignore list).  Gated files are structure-only.
  stage 1  importance   -> a 0..1 score mixing six cheap signals:
             0.25 centrality   PageRank over an import graph built from the
                               2 KB head reads the indexer already makes
                               (idea: Aider repo-map / grepmap; pure-python
                               power iteration, no networkx/scipy)
             0.10 hub          out-degree (orchestrator files that wire
                               features together)
             0.20 recency      exp(-age_days / 21) on connector mtime
             0.20 path role    entry/core names and dirs up, tests/fixtures/
                               examples/migrations down, times a depth prior
                               (grepmap)
             0.15 head density definitions per KB in the head, docstring bonus,
                               license/data-like penalty
             0.10 size         sweet spot 2-40 KB
           then multipliers: sibling redundancy (>20 same-ext files in one dir)
           and +50% for files changed since the previous index (incremental).
  stage 2  tiers        -> A: top ~12% (capped by an enrichment budget) go
                               Laya -> qwen exactly as before.
                           B: next ~25% go to Laya; qwen only while budget lasts.
                           C: rest are structure-only (path + symbol counts),
                               still findable via the UA structure graph.

Laya stays the content judge for A/B; this module only decides who reaches it.
Tunables via env: UYP_KEYFILE (on|off), UYP_KEYFILE_TIER_A (0.12),
UYP_KEYFILE_TIER_B (0.25), UYP_KEYFILE_MAX_ENRICH (absolute qwen budget, files),
UYP_KEYFILE_MIN_A (floor for tier A, default 15).
"""
from __future__ import annotations

import math
import os
import posixpath
import re
import time
from collections import Counter, defaultdict

WEIGHTS = {"centrality": 0.25, "hub": 0.10, "recency": 0.20,
           "path_role": 0.20, "head_density": 0.15, "size": 0.10}

# ---------------------------------------------------------------- stage 0 --
# Path patterns: Linguist vendor.yml/documentation.yml (subset) + repomix
# defaultIgnore.  Matched against the posix relpath, case-insensitive.
_VENDOR_PATH = re.compile(r"""(?ix)
  (^|/)(vendor|vendors|third[_-]?party|external|extern|deps|bower_components|
        node_modules|jspm_packages|Pods|Carthage|\.yarn|\.pnpm-store|
        dist|build|out|target|coverage|\.next|\.nuxt|\.svelte-kit|\.turbo|
        \.cache|\.parcel-cache|\.gradle|DerivedData|site-packages|
        \.venv|venv|env|__pycache__|\.tox|\.mypy_cache|\.pytest_cache|
        _build|htmlcov|\.terraform)/
  | (^|/)(jquery|bootstrap|d3|three|lodash|underscore|moment|react(-dom)?|
          vue|angular|chart|highlight|prism|mathjax|font-?awesome)
         ([.-][\d.]+)?(\.min)?\.(js|css)$
  | (^|/)(gradlew(\.bat)?|mvnw(\.cmd)?)$
  | (^|/)\.(idea|vscode|github/ISSUE_TEMPLATE)/
""")
_LOCKFILES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "poetry.lock",
    "pipfile.lock", "cargo.lock", "gemfile.lock", "composer.lock", "go.sum",
    "podfile.lock", "package.resolved", "flake.lock", "uv.lock", "pdm.lock",
    "mix.lock", "pubspec.lock", "packages.lock.json", "shrinkwrap.yaml",
}
_GENERATED_SUFFIX = re.compile(
    r"(?i)(\.min\.(js|css)|\.map|\.pb\.go|_pb2(_grpc)?\.py|\.pb\.(h|cc)|\.g\.dart|"
    r"\.freezed\.dart|\.designer\.cs|\.generated\.\w+|_generated\.\w+|\.gen\.\w+|"
    r"\.d\.ts\.map|\.snap|\.pyc|\.class|\.ipynb_checkpoints)$")
# Header markers (Linguist generated.rb; nearly all live in the first lines).
_GENERATED_HEAD = re.compile(r"""(?ix)
    code\ generated\ .{0,80}do\ not\ edit
  | @generated\b
  | auto-?generated\ (file|code|by)
  | this\ file\ (was|is)\ (automatically\ )?generated
  | generated\ by\ the\ protocol\ buffer\ compiler
  | autogenerated\ by\ thrift
  | generated\ by\ (cython|swig|flatc|sqlc|protoc|openapi|swagger|graphql-codegen|bindgen)
  | do\ not\ (edit|modify)\ (this\ file|manually|by\ hand)
""")


def _minified(rel: str, head: str) -> bool:
    if not head:
        return False
    if "\n" not in head[:2048] and len(head) >= 1024:
        return True  # one long line: bundle or extension-less binary
    ext = posixpath.splitext(rel)[1].lower()
    lines = head.split("\n")[:40]
    avg = sum(len(ln) for ln in lines) / max(len(lines), 1)
    # Linguist uses 110 for js/css.  Other text (html with inline styles,
    # markdown tables) legitimately has a few long lines; real bundles in a
    # 2 KB head average well over 500.
    limit = 110 if ext in {".js", ".mjs", ".cjs", ".css"} else 500
    return avg > limit


def hard_gate(rel: str, size: int, head: str = "") -> str | None:
    """Return a reason string when the file is never worth a model call."""
    rel = rel.replace("\\", "/")
    base = posixpath.basename(rel).lower()
    if size == 0:
        return "empty"
    if base in _LOCKFILES or base.endswith(".lock"):
        return "lockfile"
    if _GENERATED_SUFFIX.search(rel):
        return "generated-suffix"
    if _VENDOR_PATH.search(rel):
        return "vendored-path"
    if head and _GENERATED_HEAD.search(head[:1500]):
        return "generated-marker"
    if _minified(rel, head):
        return "minified"
    return None


# ---------------------------------------------------------------- graph ----
_IMPORT_PATTERNS = [
    # python
    re.compile(r"^\s*from\s+(\.*[\w.]*)\s+import\s+([\w*, ()]+)", re.M),
    re.compile(r"^\s*import\s+([\w.]+(?:\s*,\s*[\w.]+)*)", re.M),
    # js / ts
    re.compile(r"""(?:import|export)\s[^'"]*?from\s+['"]([^'"]+)['"]"""),
    re.compile(r"""import\s+['"]([^'"]+)['"]"""),
    re.compile(r"""require\(\s*['"]([^'"]+)['"]\s*\)"""),
    re.compile(r"""import\(\s*['"]([^'"]+)['"]\s*\)"""),
    # c / c++ / objc local includes
    re.compile(r"""^\s*#\s*(?:include|import)\s+"([^"]+)\"""", re.M),
    # rust
    re.compile(r"^\s*(?:pub\s+)?mod\s+(\w+)\s*;", re.M),
    re.compile(r"^\s*use\s+(?:crate|super|self)::([\w:]+)", re.M),
    # go (single + block)
    re.compile(r"""^\s*import\s+(?:\w+\s+)?"([^"]+)\"""", re.M),
    # shell source
    re.compile(r"""^\s*(?:source|\.)\s+['"]?([\w./-]+\.sh)""", re.M),
]
_GO_BLOCK = re.compile(r"import\s*\(([^)]*)\)", re.S)
_DOC_EXT = {".md", ".markdown", ".rst"}
_MD_LINK = re.compile(r"\]\(\s*<?([^)\s>]+?\.(?:md|markdown|rst|py|ts|tsx|js|go|rs|swift))(?:#[^)\s]*)?>?\s*\)")
_CODE_EXT = {".py", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".swift", ".rs",
             ".go", ".c", ".h", ".cc", ".cpp", ".hpp", ".m", ".mm", ".java", ".kt",
             ".rb", ".php", ".cs", ".dart", ".vue", ".svelte", ".sh", ".lua", ".scala"}


def extract_imports(rel: str, head: str) -> list[str]:
    if not head:
        return []
    refs: list[str] = []
    for pat in _IMPORT_PATTERNS:
        for m in pat.finditer(head):
            if pat.pattern.startswith("^\\s*from") and m.group(1).strip("."):
                mod = m.group(1)
                refs.append(mod)
                # "from pkg import a, b" may name submodules
                for name in re.split(r"[,\s()]+", m.group(2)):
                    if name and name != "*":
                        refs.append(f"{mod}.{name}")
            elif pat.pattern.startswith("^\\s*from"):
                # "from . import x" / "from .. import x": relative siblings
                for name in re.split(r"[,\s()]+", m.group(2)):
                    if name and name != "*":
                        refs.append(m.group(1) + name)
            else:
                for part in m.group(1).split(","):
                    if part.strip():
                        refs.append(part.strip())
    for block in _GO_BLOCK.finditer(head):
        refs.extend(re.findall(r'"([^"]+)"', block.group(1)))
    if posixpath.splitext(rel)[1].lower() in _DOC_EXT:
        # markdown links make a doc graph: README -> docs/PLAN.md etc.
        for target in _MD_LINK.findall(head):
            target = target.split("#")[0].strip()
            if target and not target.startswith(("/", ".")):
                target = "./" + target
            if target:
                refs.append(target)
    return refs


class _Resolver:
    """Map import strings to manifest relpaths by path suffix / module stem."""

    def __init__(self, relpaths):
        self.by_suffix: dict[str, set[str]] = defaultdict(set)
        for rel in relpaths:
            stem, ext = posixpath.splitext(rel)
            if ext.lower() not in _CODE_EXT and ext.lower() not in _DOC_EXT | {".json", ".css", ".scss"}:
                continue
            parts = stem.split("/")
            if parts[-1] in {"__init__", "index", "mod", "main"} and len(parts) > 1:
                parts_pkg = parts[:-1]
                for i in range(len(parts_pkg)):
                    self.by_suffix["/".join(parts_pkg[i:])].add(rel)
            for i in range(len(parts)):
                self.by_suffix["/".join(parts[i:])].add(rel)

    def resolve(self, src: str, ref: str) -> set[str]:
        ref = ref.strip()
        if not ref or ref.startswith(("http:", "https:", "node:")):
            return set()
        src_dir = posixpath.dirname(src)
        if ref.startswith("."):
            if "/" in ref or ref in {".", ".."}:          # js relative path
                key = posixpath.normpath(posixpath.join(src_dir, ref))
            else:                                          # python relative
                dots = len(ref) - len(ref.lstrip("."))
                base = src_dir
                for _ in range(dots - 1):
                    base = posixpath.dirname(base)
                key = posixpath.join(base, ref.lstrip(".").replace(".", "/"))
            if posixpath.splitext(key)[1].lower() in _CODE_EXT | _DOC_EXT:
                key = posixpath.splitext(key)[0]
            if key.startswith("../"):
                return set()  # escapes the grant root
            hits = self.by_suffix.get(key.lstrip("./"), set())
            return {h for h in hits if h != src}
        key = ref.replace("::", "/").replace(".", "/") if "/" not in ref else ref
        key = key.lstrip("@~/").rstrip("/")
        key = posixpath.splitext(key)[0] if posixpath.splitext(key)[1] in _CODE_EXT else key
        segs = key.split("/")
        # longest suffix first: "pkg/sub/mod" -> "sub/mod" -> "mod"
        for i in range(len(segs)):
            hits = self.by_suffix.get("/".join(segs[i:]))
            if hits:
                if len(hits) > 3 and i == len(segs) - 1:
                    return set()  # bare common stem (utils, index): ambiguous
                return {h for h in hits if h != src}
        return set()


def pagerank(nodes, edges, damping=0.85, iters=40, tol=1e-6) -> dict[str, float]:
    """Plain power iteration; edges = {src: set(dst)} (importer -> imported)."""
    n = len(nodes)
    if n == 0:
        return {}
    rank = dict.fromkeys(nodes, 1.0 / n)
    out_deg = {u: len(edges.get(u, ())) for u in nodes}
    incoming = defaultdict(list)
    for u, vs in edges.items():
        for v in vs:
            incoming[v].append(u)
    for _ in range(iters):
        dangling = sum(rank[u] for u in nodes if out_deg[u] == 0)
        new = {}
        for v in nodes:
            s = sum(rank[u] / out_deg[u] for u in incoming.get(v, ()))
            new[v] = (1 - damping) / n + damping * (s + dangling / n)
        delta = sum(abs(new[u] - rank[u]) for u in nodes)
        rank = new
        if delta < tol:
            break
    return rank


