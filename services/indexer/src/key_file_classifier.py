_ENTRY_BASENAMES = {"main", "app", "index", "server", "cli", "routes", "router", "models",
                    "model", "schema", "schemas", "store", "api", "__main__", "core",
                    "engine", "pipeline", "service", "handler", "handlers", "manage",
                    "setup", "config", "settings", "agent", "controller", "views"}
_PROGRESS_DOCS = {"readme", "architecture", "design", "todo", "roadmap", "changelog",
                  "plan", "notes", "status", "progress", "agents", "claude", "spec",
                  "overview", "contributing", "backlog", "execution_plan"}
_CORE_DIRS = {"src", "app", "lib", "core", "server", "services", "service", "components",
              "pkg", "internal", "cmd", "api", "backend", "frontend", "agents", "engine"}
_LOW_DIRS = re.compile(r"(?i)(^|/)(tests?|__tests__|spec|specs|fixtures?|examples?|samples?|"
                       r"demos?|migrations?|mocks?|__mocks__|stories|storybook|scripts|"
                       r"generated|benchmarks?|e2e|testdata|assets|static|public|locales?|"
                       r"i18n|docs?/api)/")
_LOW_NAMES = re.compile(r"(?i)(^test_|_test\.|\.test\.|\.spec\.|^conftest\.py$|\.stories\.|"
                        r"_mock\.|\.mock\.|^license|^copying|^notice|^\.)")
_DEF_RE = re.compile(r"(?m)^\s*(?:export\s+)?(?:default\s+)?(?:async\s+)?(?:pub(?:\(\w+\))?\s+)?"
                     r"(?:def|class|function|interface|struct|enum|trait|impl|fn|func|"
                     r"protocol|extension|type\s+\w+\s*=|const\s+\w+\s*=\s*\(|"
                     r"(?:public|private|protected|static)\s+[\w<>\[\]]+\s+\w+\s*\()")
_DOC_RE = re.compile(r'^\s*(?:"""|\'\'\'|/\*\*|//!|///|#\s+\w|<!--|# )', re.M)
# Planning / design / decision docs carry project progress.
_PROGRESS_WORDS = re.compile(r"(?i)(plan|design|architect|roadmap|status|progress|report|"
                             r"acceptance|adr|spec|protocol|contract|strategy|decision|"
                             r"notes|todo|backlog|changelog|audit|retro|milestone|proposal|rfc)")
_LICENSE_RE = re.compile(r"(?i)(copyright|licen[cs]ed under|permission is hereby granted|"
                         r"spdx-license-identifier|all rights reserved)")


def path_role(rel: str) -> float:
    rel = rel.replace("\\", "/")
    stem = posixpath.splitext(posixpath.basename(rel))[0].lower()
    ext = posixpath.splitext(rel)[1].lower()
    depth = rel.count("/")
    if _LOW_DIRS.search(rel) or _LOW_NAMES.search(posixpath.basename(rel)):
        role = 0.2
    elif stem in _PROGRESS_DOCS and ext in {".md", ".markdown", ".rst", ".txt", ""}:
        role = 1.0 if depth <= 1 else 0.8
    elif stem in _ENTRY_BASENAMES:
        role = 1.0
    elif any(seg.lower() in _CORE_DIRS for seg in rel.split("/")[:-1]):
        role = 0.75
    elif ext in _CODE_EXT:
        role = 0.6
    elif ext in _DOC_EXT and _PROGRESS_WORDS.search(rel):
        role = 0.85
    elif ext in _DOC_EXT:
        role = 0.5
    else:
        role = 0.3
    # grepmap depth prior, softened: core code often lives at depth 3-4
    prior = 1.0 if depth <= 2 else (0.8 if depth <= 4 else 0.5)
    return role * prior


def head_density(rel: str, head: str) -> float:
    if not head:
        return 0.3
    kb = max(len(head) / 1024.0, 0.25)
    defs = len(_DEF_RE.findall(head))
    score = min(defs / kb / 6.0, 1.0)  # ~6 defs/KB saturates
    first = "\n".join(head.split("\n")[:5])
    if _DOC_RE.search(first):
        score += 0.2
    ext = posixpath.splitext(rel)[1].lower()
    if ext in {".md", ".markdown", ".rst", ".txt"}:
        # prose: headings + length stand in for definitions
        heads = len(re.findall(r"(?m)^#{1,3}\s", head))
        score = max(score, min(0.3 + heads * 0.1, 0.9))
    body = head[:1500]
    if _LICENSE_RE.search(body[:600]) and defs == 0:
        score *= 0.3
    if body:
        datalike = sum(ch.isdigit() or ch in "\"',[]{}:" for ch in body) / len(body)
        if datalike > 0.4:
            score *= 0.3
    return min(score, 1.0)


def size_score(size: int) -> float:
    if 2_000 <= size <= 40_000:
        return 1.0
    if 40_000 < size <= 150_000:
        return 0.8  # big modules are often the core (query_api, mcp_server)
    if size < 300 or size > 150_000:
        return 0.2
    return 0.7  # 300 B - 2 KB


def recency(mtime, now=None) -> float:
    now = now or time.time()
    try:
        ts = float(mtime)
    except (TypeError, ValueError):
        try:  # connector may send ISO strings
            from datetime import datetime
            ts = datetime.fromisoformat(str(mtime).replace("Z", "+00:00")).timestamp()
        except Exception:
            return 0.5
    age_days = max((now - ts) / 86400.0, 0.0)
    return math.exp(-age_days / 21.0)


def _percentiles(values: dict[str, float]) -> dict[str, float]:
    if not values:
        return {}
    order = sorted(values, key=lambda k: values[k])
    n = len(order)
    if n == 1:
        return {order[0]: 1.0}
    out, i = {}, 0
    while i < n:  # ties share a percentile
        j = i
        while j + 1 < n and values[order[j + 1]] == values[order[i]]:
            j += 1
        pct = ((i + j) / 2) / (n - 1)
        for k in order[i:j + 1]:
            out[k] = pct
        i = j + 1
    return out


# ------------------------------------------------------- embedded projects --
_PROJECT_MANIFESTS = {"package.json", "pyproject.toml", "setup.py", "cargo.toml", "go.mod",
                      "pom.xml", "build.gradle", "gemfile", "composer.json", "pubspec.yaml"}
_VENDOR_MARKERS = re.compile(r"(?i)^(upstream|provenance|vendor(ed)?|third[_-]?party(_notices)?)(\.\w+)?$")
_LICENSE_FILE = re.compile(r"(?i)^(license|licence|copying)(\.\w+)?$")
_EMBEDDED_DOCS = {"readme", "design", "architecture", "upstream", "provenance", "changelog"}


def detect_embedded_roots(rels) -> set[str]:
    """Sub-folders that are a copied-in third-party project, not the owner's work.

    Signals (a project manifest is always required):
      * an UPSTREAM / PROVENANCE / VENDOR marker file next to it, or
      * its own LICENSE while holding more than half of all files - a large
        bundled dependency, e.g. a full upstream repo dropped into a demo.
    Only the outermost such folder counts.  The repository root never does.
    """
    by_dir: dict[str, set[str]] = defaultdict(set)
    for rel in rels:
        d, base = posixpath.split(rel.replace("\\", "/"))
        by_dir[d].add(base.lower())
    total = max(len(rels), 1)
    roots = []
    for d, names in by_dir.items():
        if not d or not (names & _PROJECT_MANIFESTS):
            continue
        marker = any(_VENDOR_MARKERS.match(n) for n in names)
        licensed = any(_LICENSE_FILE.match(n) for n in names)
        share = sum(1 for r in rels if r.startswith(d + "/")) / total
        if marker or (licensed and share > 0.5):
            roots.append(d)
    roots.sort(key=len)
    outer: set[str] = set()
    for d in roots:
        if not any(d.startswith(o + "/") for o in outer):
            outer.add(d)
    return outer


def _embedded_root(rel: str, roots: set[str]) -> str | None:
    for root in roots:
        if rel.startswith(root + "/"):
            return root
    return None


# ------------------------------------------------------------- classify ----
def classify(files, heads, *, changed=None, tier_a=None, tier_b=None,
             max_enrich=None, min_a=None, now=None) -> dict[str, dict]:
    """files: manifest entries ({relpath,size,mtime}); heads: {relpath: str}.

    Returns {relpath: {"score", "tier" (A|B|C|gate), "gate", "features"}}.
    """
    tier_a = float(os.environ.get("UYP_KEYFILE_TIER_A", tier_a if tier_a is not None else 0.12))
    tier_b = float(os.environ.get("UYP_KEYFILE_TIER_B", tier_b if tier_b is not None else 0.25))
    min_a = int(os.environ.get("UYP_KEYFILE_MIN_A", min_a if min_a is not None else 15))
    env_budget = os.environ.get("UYP_KEYFILE_MAX_ENRICH")
    if env_budget:
        max_enrich = int(env_budget)
    changed = set(changed or ())

    out: dict[str, dict] = {}
    live = []
    for f in files:
        rel = f["relpath"]
        gate = hard_gate(rel, int(f.get("size") or 0), heads.get(rel, ""))
        if gate:
            out[rel] = {"score": 0.0, "tier": "gate", "gate": gate, "features": {}}
        else:
            live.append(f)

    rels = [f["relpath"] for f in live]
    resolver = _Resolver(rels)
    edges: dict[str, set[str]] = {}
    for rel in rels:
        targets = set()
        for ref in extract_imports(rel, heads.get(rel, "")):
            targets |= resolver.resolve(rel, ref)
        if targets:
            edges[rel] = targets
    pr = pagerank(rels, edges)
    out_deg = {r: float(len(edges.get(r, ()))) for r in rels}

    cent = _percentiles(pr)
    hub = _percentiles(out_deg) if any(out_deg.values()) else dict.fromkeys(rels, 0.0)
    in_graph = set(edges) | {v for vs in edges.values() for v in vs}
    sibling = Counter((posixpath.dirname(r), posixpath.splitext(r)[1].lower()) for r in rels)

    scored = []
    for f in live:
        rel = f["relpath"]
        role = path_role(rel)
        feats = {
            # files outside the import graph (docs, unresolved imports) get a
            # neutral centrality, not zero, so non-code projects still rank
            "centrality": cent.get(rel, 0.0) if rel in in_graph else 0.3,
            "hub": hub.get(rel, 0.0),
            "recency": recency(f.get("mtime"), now),
            "path_role": role,
            "head_density": head_density(rel, heads.get(rel, "")),
            "size": size_score(int(f.get("size") or 0)),
        }
        if role < 0.3:
            feats["hub"] = 0.0  # tests/fixtures import everything; not orchestrators
        s = sum(WEIGHTS[k] * v for k, v in feats.items())
        n_sib = sibling[(posixpath.dirname(rel), posixpath.splitext(rel)[1].lower())]
        if n_sib > 20:
            s *= math.sqrt(20.0 / n_sib)
        if rel in changed:
            s = min(s * 1.5, 1.0)
        scored.append((s, rel, feats))

    scored.sort(key=lambda t: (-t[0], t[1]))

    # Embedded third-party projects (e.g. a bundled upstream repo) would
    # otherwise win the percentile race by sheer size.  Their files stay
    # findable (structure-only + UA graph); only their top-level docs get a
    # Laya look.  Tier sizes are computed over the owner's own files.
    embedded_roots = set()
    if os.environ.get("UYP_KEYFILE_EMBEDDED", "demote").strip().lower() != "keep":
        embedded_roots = detect_embedded_roots(rels)
    own = [t for t in scored if not _embedded_root(t[1], embedded_roots)]
    if not own:  # the whole project is "embedded": nothing to demote against
        embedded_roots, own = set(), scored
    emb = [t for t in scored if _embedded_root(t[1], embedded_roots)]

    n = len(own)
    n_a = max(min(min_a, n), math.ceil(n * tier_a)) if n else 0
    if max_enrich is not None:
        n_a = min(n_a, max(int(max_enrich), 0))
    n_b = math.ceil(n * tier_b)
    for i, (s, rel, feats) in enumerate(own):
        tier = "A" if i < n_a else ("B" if i < n_a + n_b else "C")
        out[rel] = {"score": round(s, 4), "tier": tier, "gate": None,
                    "rank": i + 1, "features": {k: round(v, 3) for k, v in feats.items()}}
    for j, (s, rel, feats) in enumerate(emb):
        root = _embedded_root(rel, embedded_roots)
        inner = rel[len(root) + 1:]
        stem = posixpath.splitext(inner)[0].lower()
        tier = "B" if "/" not in inner and stem in _EMBEDDED_DOCS else "C"
        out[rel] = {"score": round(s, 4), "tier": tier, "gate": None, "embedded": root,
                    "rank": n + j + 1, "features": {k: round(v, 3) for k, v in feats.items()}}
    return out


def enabled() -> bool:
    return os.environ.get("UYP_KEYFILE", "on").strip().lower() not in {"off", "0", "false", "no"}
