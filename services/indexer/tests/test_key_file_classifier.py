import time
import unittest
from pathlib import Path

import sys

sys.path.insert(0, str(Path(__file__).parents[1] / "src"))

import key_file_classifier as kfc  # noqa: E402

NOW = 1_760_000_000.0


def f(rel, size=5000, age_days=1.0):
    return {"relpath": rel, "size": size, "mtime": NOW - age_days * 86400}


class TestHardGate(unittest.TestCase):
    def test_vendor_lock_generated_minified(self):
        self.assertEqual(kfc.hard_gate("node_modules/x/index.js", 10), "vendored-path")
        self.assertEqual(kfc.hard_gate("third_party/lib/a.c", 10), "vendored-path")
        self.assertEqual(kfc.hard_gate("static/jquery-3.6.0.min.js", 10), "generated-suffix")
        self.assertEqual(kfc.hard_gate("web/package-lock.json", 10), "lockfile")
        self.assertEqual(kfc.hard_gate("Cargo.lock", 10), "lockfile")
        self.assertEqual(kfc.hard_gate("api/v1/user_pb2.py", 10), "generated-suffix")
        self.assertEqual(kfc.hard_gate("a/b.go", 10, "// Code generated by protoc-gen-go. DO NOT EDIT.\n"),
                         "generated-marker")
        self.assertEqual(kfc.hard_gate("bundle.js", 10, "var a=" + "x" * 2000), "minified")
        self.assertEqual(kfc.hard_gate("empty.py", 0), "empty")

    def test_normal_source_passes(self):
        head = '"""Router."""\nimport os\n\ndef route(x):\n    return x\n'
        self.assertIsNone(kfc.hard_gate("src/router.py", 900, head))
        self.assertIsNone(kfc.hard_gate("README.md", 900, "# Project\n\nText"))


class TestImportGraph(unittest.TestCase):
    def test_python_and_js_resolution(self):
        rels = ["pkg/core.py", "pkg/util.py", "pkg/__init__.py", "web/src/app.ts",
                "web/src/lib/api.ts", "web/src/lib/index.ts"]
        r = kfc._Resolver(rels)
        self.assertEqual(r.resolve("pkg/__init__.py", "pkg.core"), {"pkg/core.py"})
        self.assertEqual(r.resolve("pkg/core.py", ".util"), {"pkg/util.py"})
        self.assertEqual(r.resolve("web/src/app.ts", "./lib/api"), {"web/src/lib/api.ts"})
        self.assertEqual(r.resolve("web/src/app.ts", "./lib"), {"web/src/lib/index.ts"})
        self.assertEqual(r.resolve("pkg/core.py", "requests"), set())

    def test_extract_imports(self):
        py = "from pkg import core, util\nimport os, json\nfrom .sib import x\n"
        refs = kfc.extract_imports("pkg/a.py", py)
        self.assertIn("pkg.core", refs)
        self.assertIn("os", refs)
        self.assertIn(".sib", refs)
        js = "import React from 'react'\nimport { a } from \"./lib/api\"\nconst b = require('./b')\n"
        refs = kfc.extract_imports("x.ts", js)
        self.assertIn("./lib/api", refs)
        self.assertIn("./b", refs)

    def test_pagerank_hub_gets_most(self):
        nodes = ["a", "b", "c", "core"]
        pr = kfc.pagerank(nodes, {"a": {"core"}, "b": {"core"}, "c": {"core"}})
        self.assertEqual(max(pr, key=pr.get), "core")
        self.assertAlmostEqual(sum(pr.values()), 1.0, places=4)


class TestClassify(unittest.TestCase):
    def setUp(self):
        self.files = [f("src/core.py"), f("src/a.py"), f("src/b.py"), f("src/c.py"),
                      f("tests/test_core.py"), f("README.md", 3000),
                      f("docs/old_notes.md", 3000, age_days=400),
                      f("node_modules/x/index.js"), f("package-lock.json", 90000)]
        self.files += [f(f"migrations/{i:04d}_auto.py", 800, age_days=200) for i in range(30)]
        body = "\ndef run():\n    pass\nclass K:\n    pass\n"
        self.heads = {x["relpath"]: "import os\n" + body for x in self.files}
        for n in ("a", "b", "c"):
            self.heads[f"src/{n}.py"] = "from src import core\n" + body
        self.heads["tests/test_core.py"] = "from src import core\n" + body
        self.heads["README.md"] = "# Project\n## Goals\n## Status\ntext\n"

    def test_tiers_and_order(self):
        out = kfc.classify(self.files, self.heads, now=NOW, tier_a=0.12, tier_b=0.25, min_a=3)
        self.assertEqual(out["node_modules/x/index.js"]["tier"], "gate")
        self.assertEqual(out["package-lock.json"]["tier"], "gate")
        self.assertEqual(out["src/core.py"]["tier"], "A")
        self.assertEqual(out["README.md"]["tier"], "A")
        self.assertGreater(out["src/core.py"]["score"], out["tests/test_core.py"]["score"])
        self.assertGreater(out["src/a.py"]["score"], out["migrations/0001_auto.py"]["score"])
        # every non-migration file outranks every migration; most migrations are C
        real = [k for k, v in out.items() if v["tier"] != "gate" and not k.startswith("migrations/")]
        worst_real = max(out[k]["rank"] for k in real)
        best_mig = min(v["rank"] for k, v in out.items() if k.startswith("migrations/"))
        self.assertLess(worst_real, best_mig)
        self.assertGreater(sum(out[f"migrations/{i:04d}_auto.py"]["tier"] == "C" for i in range(30)), 20)
        live = [v for v in out.values() if v["tier"] != "gate"]
        self.assertEqual(sorted(v["rank"] for v in live), list(range(1, len(live) + 1)))

    def test_budget_caps_tier_a(self):
        out = kfc.classify(self.files, self.heads, now=NOW, max_enrich=1, min_a=3)
        self.assertEqual(sum(v["tier"] == "A" for v in out.values()), 1)

    def test_changed_boost(self):
        base = kfc.classify(self.files, self.heads, now=NOW)
        boosted = kfc.classify(self.files, self.heads, now=NOW, changed={"docs/old_notes.md"})
        self.assertGreater(boosted["docs/old_notes.md"]["score"], base["docs/old_notes.md"]["score"])

    def test_embedded_upstream_project_is_demoted(self):
        files = [f("app.py"), f("README.md", 3000), f("lib/core.py")]
        files += [f("vendorlib/package.json", 900), f("vendorlib/UPSTREAM.md", 900),
                  f("vendorlib/README.md", 3000), f("vendorlib/LICENSE", 1000)]
        files += [f(f"vendorlib/src/m{i}.ts") for i in range(200)]
        heads = {x["relpath"]: "export function run() {}\n" for x in files}
        heads["app.py"] = "from lib import core\n\ndef main():\n    pass\n"
        out = kfc.classify(files, heads, now=NOW, min_a=2)
        self.assertEqual(kfc.detect_embedded_roots([x["relpath"] for x in files]), {"vendorlib"})
        tier_a = {r for r, v in out.items() if v["tier"] == "A"}
        self.assertEqual(len(tier_a), 2)  # min_a=2, sized over the 3 own files
        self.assertTrue(tier_a <= {"app.py", "lib/core.py", "README.md"})
        self.assertEqual(out["vendorlib/README.md"]["tier"], "B")
        self.assertEqual(out["vendorlib/src/m0.ts"]["tier"], "C")
        self.assertEqual(out["vendorlib/src/m0.ts"]["embedded"], "vendorlib")
        # own files always outrank embedded ones
        self.assertLess(max(out[r]["rank"] for r in ("app.py", "lib/core.py", "README.md")),
                        min(v["rank"] for v in out.values() if v.get("embedded")))

    def test_monorepo_package_without_markers_is_not_embedded(self):
        rels = ["package.json", "packages/ui/package.json", "packages/ui/src/a.ts",
                "packages/api/package.json", "packages/api/src/b.ts"]
        self.assertEqual(kfc.detect_embedded_roots(rels), set())

    def test_whole_project_never_demoted(self):
        files = [f("pkg/package.json", 900), f("pkg/UPSTREAM.md", 900), f("pkg/src/a.ts")]
        out = kfc.classify(files, {}, now=NOW)
        self.assertTrue(all("embedded" not in v for v in out.values()))

    def test_html_with_long_inline_lines_not_minified(self):
        head = "<html><head><style>" + "a{color:red}" * 30 + "</style>\n" * 6
        self.assertIsNone(kfc.hard_gate("web/index.html", 21000, head))

    def test_iso_mtime(self):
        self.assertGreater(kfc.recency(time.strftime("%Y-%m-%dT%H:%M:%S+00:00", time.gmtime())), 0.9)


if __name__ == "__main__":
    unittest.main()
